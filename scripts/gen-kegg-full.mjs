/**
 * 生成 KEGG 全量人类通路目录（372 条）→ src/data/kegg-full-catalog.ts
 * 数据源: rest.kegg.jp（已验证可访问）
 *   1. list/pathway/hsa → 全量 id + name
 *   2. get/hsaXXXXXX 批量（10/请求）→ CLASS 分类字段
 *   3. nameZh: 术语词典最长匹配机械翻译（策划 13 条由 PATHWAY_CATALOG 覆盖）
 */
import { writeFileSync } from 'node:fs';

const KEGG = 'https://rest.kegg.jp';

async function fetchText(url, timeoutMs = 20000) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), timeoutMs);
  try {
    const res = await fetch(url, { signal: ctrl.signal });
    if (!res.ok) throw new Error(`HTTP ${res.status} ${url}`);
    return await res.text();
  } finally {
    clearTimeout(timer);
  }
}

// ---------- 1. 全量列表 ----------
const listText = await fetchText(`${KEGG}/list/pathway/hsa`);
const entries = listText
  .split('\n')
  .filter((l) => l.trim().startsWith('hsa'))
  .map((l) => {
    const [id, ...rest] = l.split('\t');
    const name = rest.join('\t').replace(' - Homo sapiens (human)', '').trim();
    return { id, name };
  });
console.log(`list/pathway/hsa → ${entries.length} entries`);

// ---------- 2. CLASS 分类（批量 10/请求） ----------
const classById = new Map();
const BATCH = 10;
for (let i = 0; i < entries.length; i += BATCH) {
  const batch = entries.slice(i, i + BATCH).map((e) => e.id);
  let text = '';
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      text = await fetchText(`${KEGG}/get/${batch.join('+')}`, 25000);
      break;
    } catch (err) {
      console.error(`retry ${batch[0]}: ${err.message}`);
      if (attempt === 2) text = '';
    }
  }
  if (!text) continue;
  let curId = null;
  for (const line of text.split('\n')) {
    if (line.startsWith('ENTRY')) {
      curId = line.trim().split(/\s+/)[1];
    } else if (line.startsWith('CLASS') && curId) {
      classById.set(curId, line.replace(/^CLASS\s+/, '').trim());
    }
  }
  process.stdout.write(`\rCLASS ${Math.min(i + BATCH, entries.length)}/${entries.length}`);
}
console.log(`\nclass fetched: ${classById.size}/${entries.length}`);

